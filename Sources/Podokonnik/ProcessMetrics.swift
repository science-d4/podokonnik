import Foundation
import Darwin

struct ProcessSample {
    let uptime: Double
    let cpuSeconds: Double
    let physicalBytes: UInt64
    static func current() -> ProcessSample {
        var usage = rusage()
        getrusage(RUSAGE_SELF, &usage)
        let seconds = Double(usage.ru_utime.tv_sec + usage.ru_stime.tv_sec)
            + Double(usage.ru_utime.tv_usec + usage.ru_stime.tv_usec) / 1_000_000
        var info = task_vm_info_data_t()
        var count = mach_msg_type_number_t(MemoryLayout<task_vm_info_data_t>.size / MemoryLayout<integer_t>.size)
        let capacity = Int(count)
        let result = withUnsafeMutablePointer(to: &info) { pointer in
            pointer.withMemoryRebound(to: integer_t.self, capacity: capacity) {
                task_info(mach_task_self_, task_flavor_t(TASK_VM_INFO), $0, &count)
            }
        }
        return ProcessSample(uptime: ProcessInfo.processInfo.systemUptime, cpuSeconds: seconds,
                             physicalBytes: result == KERN_SUCCESS ? info.phys_footprint : 0)
    }
}
